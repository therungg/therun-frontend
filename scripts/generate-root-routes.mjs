// Writes src/generated/root-routes.ts: every first URL segment the app itself
// serves. The proxy checks this set before it hands a root path to a game, so
// a game named `live` can never take /live.
//
// It is generated rather than hand-kept for exactly that reason — a missed
// entry silently hands one of our own routes to a game. Runs on predev and
// prebuild; check the result in, so a build without the script still has it.
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const appDir = join(root, 'app');
const outFile = join(root, 'src', 'generated', 'root-routes.ts');

/** A route group — `(new-layout)` — is not a URL segment; look inside it. */
const isGroup = (name) => name.startsWith('(') && name.endsWith(')');
/** `[username]`, `[[...slug]]`: dynamic, so it claims nothing by name. */
const isDynamic = (name) => name.startsWith('[');
/** `_components`, `.well-known`: private folders, never routed. */
const isPrivate = (name) => name.startsWith('_') || name.startsWith('.');

function collect(dir, into) {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
        if (!entry.isDirectory()) continue;
        const { name } = entry;
        if (isPrivate(name)) continue;
        if (isGroup(name)) {
            collect(join(dir, name), into);
            continue;
        }
        if (isDynamic(name)) continue;
        into.add(name.toLowerCase());
    }
}

const segments = new Set();
collect(appDir, segments);

// Served from public/ or by next.config rewrites rather than app/, so the
// folder walk cannot see them.
const extra = ['favicon.ico', 'robots.txt', 'sitemap.xml', 'opensearch.xml'];
for (const name of extra) segments.add(name);

const sorted = [...segments].sort();

const body = `// GENERATED by scripts/generate-root-routes.mjs — do not edit.
// Every first URL segment the app serves itself. Regenerate with
// \`node scripts/generate-root-routes.mjs\` (predev/prebuild do it for you).

export const ROOT_ROUTES: ReadonlySet<string> = new Set([
${sorted.map((s) => `    '${s}',`).join('\n')}
]);
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body);
console.log(`root-routes: ${sorted.length} segments`);
