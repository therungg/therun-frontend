// Writes src/generated/root-names.ts: the names games answer to at the site
// root, baked in at build time.
//
// It is not fetched at runtime. The proxy's isolate is torn down when the
// response ends, so a background refresh never survives to populate a cache —
// every request re-fetched and every fetch was killed mid-flight. Awaiting it
// instead would put a ~1s backend round trip in front of page requests. Games
// worth a root URL appear rarely, so a set that refreshes on deploy is the
// right trade.
//
// Failure is not fatal: an empty set means the proxy claims nothing and root
// paths go to the user route, which is the same fail-open behaviour it has
// when the flag is off. A build must not break over this.
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'src', 'generated', 'root-names.ts');

const TIMEOUT_MS = 30000;

function write(slugs, names, note) {
    const body = `// GENERATED by scripts/generate-root-names.mjs — do not edit.
// ${note}
// Regenerate with \`node scripts/generate-root-names.mjs\` (prebuild does it).

const SLUGS = ${JSON.stringify(slugs)};
const NAMES = ${JSON.stringify(names)};

export const ROOT_GAME_SLUGS: ReadonlySet<string> = new Set(SLUGS);
export const ROOT_GAME_NAMES: ReadonlySet<string> = new Set(NAMES);
`;
    mkdirSync(dirname(outFile), { recursive: true });
    writeFileSync(outFile, body);
}

async function main() {
    const base = process.env.NEXT_PUBLIC_DATA_URL;
    if (!base) {
        console.warn(
            'root-names: NEXT_PUBLIC_DATA_URL unset, writing empty set',
        );
        if (!existsSync(outFile))
            write([], [], 'NEXT_PUBLIC_DATA_URL was unset at build time.');
        return;
    }

    try {
        const response = await fetch(`${base}/games?view=root-names`, {
            signal: AbortSignal.timeout(TIMEOUT_MS),
        });
        if (!response.ok) throw new Error(`responded ${response.status}`);

        const body = await response.json();
        const slugs = (body?.result?.slugs ?? []).map((s) => s.toLowerCase());
        const names = (body?.result?.names ?? []).map((s) => s.toLowerCase());

        write(
            slugs,
            names,
            `${slugs.length} slugs and ${names.length} names, as of this build.`,
        );
        console.log(`root-names: ${slugs.length} slugs, ${names.length} names`);
    } catch (error) {
        console.warn(
            `root-names: fetch failed (${error.message}); keeping whatever is checked in`,
        );
        if (!existsSync(outFile))
            write(
                [],
                [],
                'The build-time fetch failed and no set was checked in.',
            );
    }
}

await main();
